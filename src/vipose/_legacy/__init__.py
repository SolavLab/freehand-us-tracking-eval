"""The original evaluation code, ported verbatim.

These five modules are **byte-identical** to the versions in the source tree
that produced the published results. Nothing here has been reformatted, renamed
or tidied, and that is the point: the golden master in ``tests/golden`` was
generated by exactly these bytes, so any behavioural difference between this
package and the published numbers can only come from code outside this
directory.

They are scheduled for replacement. ``vipose`` proper will absorb them module by
module -- reference I/O, geometry, synchronization, calibration, metrics -- each
step gated against the golden master. Until then ``vipose.evaluate`` drives them
through a compatibility bridge.

Known properties, all of which the replacement fixes:

* ``plot_path_lib`` does ``from SynchronizationNew import *`` and
  ``SynchronizationNew`` defines no ``__all__``, so the star also re-exports
  numpy, pandas, pyplot, scipy interpolators -- and ``os.error``, via
  ``from os import error`` on its first line.
* Residual values are returned *by the plotting functions*, so results cannot be
  computed without drawing figures.
* Those figures are never closed. One process evaluating all four recordings
  passes 2 GB within minutes, because stage 3 runs roughly a hundred
  calibrations per recording. ``vipose.evaluate`` therefore uses one process per
  recording.
* Importing ``plot_path_lib`` mutates global state: it selects a matplotlib
  backend from ``DISPLAY``, calls ``plt.ion()`` and sets
  ``QT_QPA_PLATFORM=offscreen``.

Because the modules import each other by bare name (``from plot_path_lib import
...``), this directory is placed on ``sys.path`` rather than their imports being
rewritten -- rewriting them would break the byte-identity that makes them
useful as a reference.
"""

